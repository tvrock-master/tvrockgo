const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const path=require('node:path');
const fs=require('node:fs');
const {pathToFileURL}=require('node:url');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1000,height:600}});
    await page.clock.install();
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.route('https://fonts.googleapis.com/**',route=>route.abort());
    if(process.env.MDI_FIXTURE_DIR)await page.route('https://cdn.jsdelivr.net/npm/@mdi/font@latest/**',route=>{
      const css=new URL(route.request().url()).pathname.endsWith('.css');
      return route.fulfill({contentType:css?'text/css':'font/woff2',headers:{'Access-Control-Allow-Origin':'*'},body:fs.readFileSync(path.join(process.env.MDI_FIXTURE_DIR,css?'materialdesignicons.min.css':'materialdesignicons-webfont.woff2'))});
    });
    await page.addInitScript(()=>{
      window.operations=[];
      window.rockbar={onUpdate:callback=>window.updateRockbar=callback,settings:async()=>({server:'http://localhost'}),connect:async()=>({}),watchDevice:async()=>{},setMode:async()=>{},playback:async(...args)=>{operations.push(args);return {ok:true};}};
    });
    await page.goto(pathToFileURL(path.resolve(__dirname,'../src/index.html')).href);
    await page.evaluate(()=>document.fonts.load('30px "Material Design Icons"'));
    assert.deepEqual(errors,[]);
    await page.evaluate(()=>{
      updateRockbar({type:'status',value:{connected:true}});
      updateRockbar({type:'devices',value:[{ID:'REC01',State:0},{ID:'PBK01',Kind:'playback',State:2,Playback:{session:'one',title:'録画した番組のタイトル',phase:'playing',generation:1,positionMs:15000,durationMs:3600000}}]});
    });
    assert.equal(await page.locator('[data-device="PBK01"]').getAttribute('aria-pressed'),'true','new Playback device is selected automatically');
    await page.locator('[data-device="REC01"]').click();
    assert.match(await page.locator('#ticker').textContent(),/REC01/);
    assert.doesNotMatch(await page.locator('#ticker').textContent(),/Playback:/);
    await page.evaluate(()=>updateRockbar({type:'playback',value:{action:'request',session:'one',deviceId:'PBK01'}}));
    assert.match(await page.locator('#ticker').textContent(),/PBK01.*再生要求受信済み/);
    assert.equal(await page.locator('[data-device="REC01"]').getAttribute('aria-pressed'),'true','receipt is visible without selecting PBK');
    await page.evaluate(()=>updateRockbar({type:'playback-status',value:{action:'status',session:'one',phase:'waiting-receiver'}}));
    assert.match(await page.locator('#ticker').textContent(),/視聴アプリ接続待ち/);
    assert.doesNotMatch(await page.locator('#ticker').textContent(),/REC01|Bitrate|Signal/,'temporary message replaces normal telemetry');
    await page.clock.runFor(4000);
    await page.locator('.ticker').hover();
    assert.equal(await page.locator('#ticker').evaluate(el=>el.getAnimations()[0].playState),'running','hover must not pause the ticker');
    await page.locator('.ticker').click();
    const tickerPosition=()=>page.locator('#ticker').evaluate(el=>el.getBoundingClientRect().left+parseFloat(getComputedStyle(el).paddingLeft)-el.parentElement.getBoundingClientRect().left);
    assert.ok(Math.abs(await tickerPosition())<1,'first character starts next to the clock');
    assert.deepEqual(await page.locator('#ticker').evaluate(el=>({animation:getComputedStyle(el).animationName,padding:getComputedStyle(el).paddingLeft,transform:getComputedStyle(el).transform})),{animation:'none',padding:'0px',transform:'none'});
    await page.clock.runFor(500);
    assert.ok(Math.abs(await tickerPosition())<1,'stopped position remains fixed after painting');
    await page.evaluate(()=>updateRockbar({type:'playback',value:{action:'status',session:'one',phase:'waiting-srt'}}));
    assert.ok(Math.abs(await tickerPosition())<1,'status updates keep the beginning at the clock while paused');
    const resume=await page.evaluate(()=>{
      const container=document.querySelector('.ticker');container.click();
      const ticker=document.querySelector('#ticker');
      return {state:ticker.getAnimations()[0].playState,position:ticker.getBoundingClientRect().left+parseFloat(getComputedStyle(ticker).paddingLeft)-container.getBoundingClientRect().left};
    });
    assert.equal(resume.state,'running');
    assert.ok(Math.abs(resume.position)<1,'resume starts at the same position');
    const resumedTime=await page.locator('#ticker').evaluate(el=>el.getAnimations()[0].currentTime);
    await page.clock.runFor(100);
    assert.ok(await page.locator('#ticker').evaluate(el=>el.getAnimations()[0].currentTime)>resumedTime);
    await page.evaluate(()=>updateRockbar({type:'playback',value:{action:'status',session:'one',phase:'playing'}}));
    await page.locator('[data-device="PBK01"]').click();
    assert.equal(await page.locator('#title').textContent(),'録画した番組のタイトル');
    assert.equal(await page.locator('#next-section').isVisible(),false);
    assert.equal(await page.locator('#schedule-section').isVisible(),false);
    assert.equal(await page.locator('#programs').isVisible(),false);
    assert.equal(await page.locator('#captions').isVisible(),true);
    assert.equal(await page.locator('#playback-panel').isVisible(),true);
    assert.match(await page.locator('#playback-position').textContent(),/\d\d:\d\d:\d\d \/ 01:00:00/);
    assert.equal(await page.locator('#playback-files-section').isVisible(),true);
    assert.equal(await page.locator('#playback-file-sort').count(),1);
    assert.equal(await page.locator('.playback-buttons button').count(),11);
    assert.equal(await page.locator('#playback-pause').getAttribute('aria-label'),'一時停止');
    assert.equal(await page.locator('#playback-stop').isVisible(),true);
    assert.equal(await page.locator('#program-progress').isVisible(),true);
    assert.equal(await page.locator('#program-progress-bar').getAttribute('aria-label'),'ファイル再生の進行状況');
    assert.equal(await page.locator('[data-device="PBK01"]').evaluate(el=>getComputedStyle(el).color),'rgb(142, 218, 255)');
    assert.equal(await page.locator('[data-device="REC01"]').evaluate(el=>getComputedStyle(el).color),'rgb(93, 206, 169)');
    assert.equal(await page.locator('[data-device="PBK01"]').evaluate(el=>getComputedStyle(el,'::before').borderTopWidth),'1px');
    assert.equal(await page.locator('#playback-position').evaluate(el=>getComputedStyle(el).fontSize),'30px');
    assert.deepEqual(await page.locator('.playback-buttons button').first().evaluate(el=>({width:el.getBoundingClientRect().width,height:el.getBoundingClientRect().height})),{width:45,height:38});
    const icons=await page.locator('.playback-icon:visible').evaluateAll(elements=>elements.map(el=>({name:el.getAttribute('class'),stroke:getComputedStyle(el).stroke,centerY:el.getBoundingClientRect().y+el.getBoundingClientRect().height/2-(el.parentElement.getBoundingClientRect().y+el.parentElement.getBoundingClientRect().height/2)})));
    assert.deepEqual(icons.map(icon=>icon.name),['playback-icon icon-skip-back','playback-icon icon-rewind','playback-icon icon-chevron-left','playback-icon icon-pause','playback-icon icon-square','playback-icon icon-chevron-right','playback-icon icon-fast-forward','playback-icon icon-skip-forward','playback-icon icon-bookmark-left','playback-icon icon-bookmark-plus','playback-icon icon-bookmark-right']);
    assert.ok(icons.every(icon=>icon.stroke==='rgb(142, 218, 255)'&&Math.abs(icon.centerY)<.5),'local line icons must be vertically centered');
    assert.equal(await page.locator('#playback-seek').isEnabled(),true);
    const order=await page.locator('#playback-panel').evaluate(el=>Array.from(el.children).map(child=>child.id||child.className));
    assert.deepEqual(order,['playback-position','playback-seek-area','playback-cm-status','playback-buttons']);
    const noVerticalOverflow=()=>page.locator('.playback-buttons').evaluate(el=>el.scrollHeight<=el.clientHeight);
    assert.equal(await noVerticalOverflow(),true);
    const beforeTick=await page.locator('#playback-position').textContent();
    await page.clock.runFor(1250);
    assert.notEqual(await page.locator('#playback-position').textContent(),beforeTick);
    const fill=await page.locator('#program-progress-bar span').first().evaluate(el=>Number(el.style.getPropertyValue('--fill')));
    assert.ok(fill>15/3600*20,'progress advances without a server report');
    await page.locator('#playback-files-section>summary').click();
    assert.equal(await page.locator('#playback-files').isVisible(),false);
    assert.equal(await page.locator('#playback-panel').isVisible(),true);
    await page.locator('#playback-files-section>summary').click();
    await page.locator('#playback-pause').click();
    await page.locator('[data-seconds="30"]').click();
    await page.locator('[data-playback="seek-start"]').click();
    await page.locator('[data-playback="seek-end"]').click();
    assert.deepEqual(await page.evaluate(()=>operations),[['PBK01','pause',0],['PBK01','seek',30],['PBK01','seek-start',0],['PBK01','seek-end',0]]);
    await page.locator('#playback-seek').evaluate(el=>{el.value='1800000';el.dispatchEvent(new Event('input',{bubbles:true}));});
    assert.match(await page.locator('#playback-position').textContent(),/^00:30:00/);
    assert.equal(await page.evaluate(()=>operations.length),4,'dragging must not send seek commands');
    await page.clock.runFor(1500);
    assert.match(await page.locator('#playback-position').textContent(),/^00:30:00/,'local clock does not overwrite the drag preview');
    await page.locator('#playback-seek').dispatchEvent('change');
    assert.deepEqual(await page.evaluate(()=>operations.at(-1)),['PBK01','seek-to',1800]);
    assert.match(await page.locator('#playback-position').textContent(),/^00:30:00/,'keep target until server acknowledgement');
    await page.evaluate(()=>{
      const device=devices.find(device=>device.ID==='PBK01');
      updateRockbar({type:'devices',value:[devices.find(device=>device.ID==='REC01'),{...device,Playback:{...device.Playback,positionMs:42000,generation:2,revision:2}}]});
    });
    assert.match(await page.locator('#playback-position').textContent(),/^00:00:42/);
    await page.screenshot({path:path.resolve(__dirname,'../../.tmp/playback-rockbar.png')});
    await page.emulateMedia({colorScheme:'dark'});
    await page.screenshot({path:path.resolve(__dirname,'../../.tmp/playback-rockbar-dark.png')});
    await page.evaluate(()=>{
      const device=devices.find(device=>device.ID==='PBK01');
      updateRockbar({type:'devices',value:[devices.find(device=>device.ID==='REC01'),{...device,Playback:{...device.Playback,phase:'paused',positionMs:43000,generation:3,revision:3}}]});
    });
    assert.equal(await page.locator('#playback-pause').getAttribute('aria-label'),'再生');
    assert.equal(await page.locator('#playback-pause .icon-play').isVisible(),true);
    assert.equal(await page.locator('#playback-stop').isVisible(),true);
    await page.clock.runFor(2000);
    assert.match(await page.locator('#playback-position').textContent(),/^00:00:43/);
    await page.locator('#playback-pause').click();
    assert.deepEqual(await page.evaluate(()=>operations.at(-1)),['PBK01','play',0]);
    await page.locator('#playback-stop').click();
    assert.deepEqual(await page.evaluate(()=>operations.at(-1)),['PBK01','stop',0]);
    await page.setViewportSize({width:680,height:360});
    const playbackFont=await page.locator('#title').evaluate(el=>getComputedStyle(el).fontSize);
    const colors=await page.evaluate(()=>{
      const row=rockbarCaptions.captionRow({ID:1,Segments:[{Text:'黄',Color:3},{Text:'赤',Color:1}]});
      document.querySelector('#caption-lines').replaceChildren(row);
      return [...row.children].map(span=>({actual:getComputedStyle(span).color,expected:span.style.color}));
    });
    assert.ok(colors.every(color=>color.actual===color.expected),'Playback retains each broadcast caption color');
    assert.notEqual(colors[0].actual,colors[1].actual);
    await page.evaluate(()=>document.body.classList.remove('playback-mode'));
    assert.equal(await page.locator('#title').evaluate(el=>getComputedStyle(el).fontSize),playbackFont,'title uses the normal device font size');
    await page.evaluate(()=>document.body.classList.add('playback-mode'));
    assert.equal(await page.locator('#capture').evaluate(el=>el.nextElementSibling.id),'playback-device');
    assert.equal(await page.locator('#playback-panel').evaluate(el=>el.getBoundingClientRect().bottom<=el.parentElement.getBoundingClientRect().bottom-2),true,'transport buttons stay visible in a short window');
    assert.equal(await noVerticalOverflow(),true);
    assert.equal(await page.locator('.playback-buttons').evaluate(el=>el.scrollWidth<=el.clientWidth),true,'all controls fit at the normal window width');
    await page.screenshot({path:path.resolve(__dirname,'../../.tmp/playback-rockbar-compact.png')});
    await page.evaluate(()=>updateRockbar({type:'playback',value:{action:'status',session:'one',phase:'failed',error:'SRT接続に失敗しました'}}));
    assert.equal(await page.locator('#ticker').textContent(),'SRT接続に失敗しました');
    await page.locator('.ticker').click();
    assert.ok(Math.abs(await tickerPosition())<1);
    await page.clock.runFor(10100);
    assert.match(await page.locator('#ticker').textContent(),/PBK01.*一時停止中/);
    assert.doesNotMatch(await page.locator('#ticker').textContent(),/失敗|受信済み/);
    assert.ok(Math.abs(await tickerPosition())<1,'normal telemetry also returns at the clock while paused');
    await page.evaluate(()=>updateRockbar({type:'notice',value:'視聴アプリを設定してください'}));
    assert.equal(await page.locator('#ticker').textContent(),'視聴アプリを設定してください');
    await page.clock.runFor(10100);
    assert.match(await page.locator('#ticker').textContent(),/PBK01.*一時停止中/);
    await page.evaluate(()=>updateRockbar({type:'devices',value:[{ID:'REC01',State:0}]}));
    assert.equal(await page.locator('[data-device="PBK01"]').count(),0);
    assert.equal(await page.locator('#playback-panel').isVisible(),false);
    assert.equal(await page.locator('#next-section').isVisible(),true);
    assert.equal(await page.locator('#schedule-section').isVisible(),true);
    assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('playback-mode')),false);
    assert.equal(await page.locator('#playback-files-section').isVisible(),false);
    assert.deepEqual(errors,[]);
    console.log('PASS: Playback panel, controls, captions, active-only devices and normal-mode restoration');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
